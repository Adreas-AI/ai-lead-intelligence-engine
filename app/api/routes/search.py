"""Free-text search and Ideal Customer Profiles."""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.api.deps import get_db, get_llm
from app.core.config import Settings, get_settings
from app.core.logging import get_logger
from app.domain.profiles import ProfileError, get_profile, list_profile_names
from app.providers.discovery.base import DiscoveryError
from app.providers.llm import LLMProvider
from app.schemas import SearchPlan, SearchRequest, SearchRunRequest, SearchRunResult
from app.services.search import SearchService

router = APIRouter(tags=["search"])
log = get_logger(__name__)


@router.post("/search/interpret", response_model=SearchPlan)
def interpret(
    body: SearchRequest,
    db: Session = Depends(get_db),
    settings: Settings = Depends(get_settings),
    llm: LLMProvider | None = Depends(get_llm),
) -> SearchPlan:
    """Show what the engine understood from a free-text query. Nothing is searched yet."""
    try:
        plan, _ = SearchService(db, settings, llm).interpret(body)
    except DiscoveryError as exc:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, str(exc)) from exc
    db.commit()  # usage events
    return plan


@router.post("/search/run", response_model=SearchRunResult)
def run(
    body: SearchRunRequest,
    db: Session = Depends(get_db),
    settings: Settings = Depends(get_settings),
    llm: LLMProvider | None = Depends(get_llm),
) -> SearchRunResult:
    """Interpret, discover, store, then enrich + score + draft the new leads."""
    try:
        return SearchService(db, settings, llm).run(body)
    except DiscoveryError as exc:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, str(exc)) from exc
    except Exception as exc:
        log.exception("search_failed", query=body.query)
        raise HTTPException(status.HTTP_502_BAD_GATEWAY, f"search failed: {exc}") from exc


@router.get("/profiles")
def profiles() -> list[dict]:
    """Available Ideal Customer Profiles (hand-written and generated by searches)."""
    out = []
    for name in list_profile_names():
        try:
            out.append(get_profile(name).summary())
        except ProfileError as exc:
            out.append({"name": name, "error": str(exc)})
    return out


@router.get("/profiles/{name}")
def profile_detail(name: str) -> dict:
    try:
        return get_profile(name).model_dump()
    except ProfileError as exc:
        raise HTTPException(status.HTTP_404_NOT_FOUND, str(exc)) from exc
